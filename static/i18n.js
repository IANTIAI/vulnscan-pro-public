  let current = 'en';

  function translateValue(value, lang) {
    if (typeof value !== 'string' || !value.trim()) return value;
    const lead = value.match(/^\s*/)?.[0] || '';
    const trail = value.match(/\s*$/)?.[0] || '';
    const core = value.slice(lead.length, value.length - trail.length || value.length);
    if (lang === 'de') {
      if (EN_DE[core]) return lead + EN_DE[core] + trail;
      for (const [, , enPattern, toGerman] of LOG_PATTERNS) {
        if (enPattern.test(core)) return lead + core.replace(enPattern, toGerman) + trail;
      }
      return value;
    }
    const canonical = EN_DE[core] || core;
    if (DE_EN[canonical]) return lead + DE_EN[canonical] + trail;
    for (const [pattern, replacement] of PATTERNS) {
      if (pattern.test(core)) return lead + core.replace(pattern, replacement) + trail;
    }
    for (const [dePattern, toEnglish] of LOG_PATTERNS) {
      if (dePattern.test(core)) return lead + core.replace(dePattern, toEnglish) + trail;
    }
    return value;
  }

  function translateNode(node, lang) {
    if (!node) return;
    if (node.nodeType === Node.TEXT_NODE) {
      const next = translateValue(node.nodeValue, lang);
      if (next !== node.nodeValue) node.nodeValue = next;
      return;
    }
    if (node.nodeType !== Node.ELEMENT_NODE && node.nodeType !== Node.DOCUMENT_NODE) return;
    if (node.nodeType === Node.ELEMENT_NODE) {
      for (const attr of ['placeholder','title','aria-label']) {
        if (node.hasAttribute(attr)) {
          const before = node.getAttribute(attr);
          const after = translateValue(before, lang);
          if (after !== before) node.setAttribute(attr, after);
        }
      }
      if (node.matches('input[type="button"],input[type="submit"]')) {
        node.value = translateValue(node.value, lang);
      }
    }
    const walker = document.createTreeWalker(node, NodeFilter.SHOW_TEXT);
    const textNodes = [];
    while (walker.nextNode()) textNodes.push(walker.currentNode);
    for (const textNode of textNodes) translateNode(textNode, lang);
  }

  function setLanguage(lang) {
    current = 'en';
    document.documentElement.lang = current;
    try { localStorage.setItem('vulnscan_language', current); } catch (_) {}
    const selector = document.getElementById('uiLanguage');
    if (selector && selector.value !== current) selector.value = current;
    translateNode(document.body, current);
    document.dispatchEvent(new CustomEvent('vulnscan:languagechange', {detail:{language:current}}));
  }

  function getLanguage() { return current; }
  window.setVulnScanLanguage = setLanguage;
  window.getVulnScanLanguage = getLanguage;
  window.vulnScanTranslate = (value) => translateValue(value, current);

  const observer = new MutationObserver(records => {
    for (const record of records) {
      if (record.type === 'characterData') translateNode(record.target, current);
      for (const node of record.addedNodes || []) translateNode(node, current);
    }
  });
  observer.observe(document.documentElement, {subtree:true, childList:true, characterData:true});

